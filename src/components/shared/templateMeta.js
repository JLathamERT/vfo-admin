// Friendly label for a bracket token's inner text: the legend entry, else a
// prettified fallback (underscores -> spaces, lower-cased, first letter capped).
export function friendlyToken(inner) {
  if (Object.prototype.hasOwnProperty.call(TOKEN_LEGEND, inner)) return TOKEN_LEGEND[inner]
  const cleaned = String(inner).replace(/_/g, ' ').trim().toLowerCase()
  if (!cleaned) return inner
  return cleaned.charAt(0).toUpperCase() + cleaned.slice(1)
}
